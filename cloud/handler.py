"""Bounded SEC collection into immutable-by-convention S3 evidence records.

The writer IAM role can only create objects using If-None-Match. It cannot read,
delete, or replace stored evidence. Account administrators remain privileged;
this is not S3 Object Lock, trusted timestamping, or a regulatory archive.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import re
import uuid
from datetime import datetime, timezone

from heltemes.sec import SecClient, SecError, select_recent_filings, validate_cik, validate_user_agent

LOGGER = logging.getLogger(__name__)
LOGGER.setLevel(logging.INFO)
ALLOWED_FORMS = frozenset({"10-Q", "10-Q/A", "10-K", "10-K/A", "8-K", "8-K/A", "20-F", "20-F/A", "6-K", "6-K/A"})
# SEC: three 5-second socket attempts, up to two 30-second Retry-After
# waits, rate limiting and overhead. S3 uses one attempt with short timeouts.
SOURCE_RESERVE_MS = 90_000
ARTIFACT_RESERVE_MS = 10_000
MANIFEST_RESERVE_MS = 15_000


class CollectionBudgetExceeded(TimeoutError):
    """Stop new source work early so the final manifest can still be saved."""


def utc_now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def json_bytes(value):
    return (json.dumps(value, sort_keys=True, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def error_details(exc):
    result = {"type": type(exc).__name__}
    if isinstance(exc, (SecError, CollectionBudgetExceeded)):
        # SecError text is generated by our client, not copied from an HTML body.
        result["message"] = str(exc)[:300]
    code = getattr(exc, "response", {}).get("Error", {}).get("Code", "")
    if isinstance(code, str) and re.fullmatch(r"[A-Za-z0-9_]{1,60}", code):
        result["code"] = code
    return result


def configuration(env):
    """Do not allow invocation payloads to change destinations or SEC identity."""
    bucket = env.get("EVIDENCE_BUCKET", "")
    if not re.fullmatch(r"[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]", bucket):
        raise ValueError("EVIDENCE_BUCKET must be a valid S3 bucket name")
    cik = validate_cik(env.get("SEC_CIK", ""))
    forms = [item.strip() for item in env.get("SEC_FORMS", "10-Q,10-Q/A").split(",")]
    if not forms or len(forms) > 10 or any(form not in ALLOWED_FORMS for form in forms):
        raise ValueError("SEC_FORMS must contain supported SEC filing forms")
    limit = int(env.get("SEC_FILING_LIMIT", "2"))
    if not 1 <= limit <= 3:
        raise ValueError("SEC_FILING_LIMIT must be between 1 and 3")
    user_agent = env.get("SEC_USER_AGENT", "")
    validate_user_agent(user_agent)
    return {"bucket": bucket, "cik": cik, "forms": forms, "limit": limit, "user_agent": user_agent}


def put_new(s3, bucket, key, body, content_type):
    """Create only. Existing content is not fetched or overwritten."""
    try:
        s3.put_object(
            Bucket=bucket,
            Key=key,
            Body=body,
            ContentType=content_type,
            ServerSideEncryption="AES256",
            IfNoneMatch="*",
            Metadata={"sha256": hashlib.sha256(body).hexdigest()},
        )
        return True
    except Exception as exc:
        response = getattr(exc, "response", {})
        if response.get("Error", {}).get("Code") in ("PreconditionFailed", "412"):
            return False
        raise


def save_artifact(s3, bucket, body, source_url, content_type):
    digest = hashlib.sha256(body).hexdigest()
    key = f"evidence/objects/sha256/{digest}"
    created = put_new(s3, bucket, key, body, content_type)
    return {
        "source_url": source_url,
        "retrieved_at": utc_now(),
        "sha256": digest,
        "bytes": len(body),
        "object_key": key,
        "object_created": created,
    }


def collect(config, s3, sec, remaining_ms=None):
    """Persist every finished run, including partial collection results.

    Raw bytes are content-addressed; each invocation receives its own manifest.
    A failed manifest upload raises instead of reporting a successful collection.
    Raw upstream response messages are not copied into manifests or logs.
    """
    def require_time(reserve):
        if remaining_ms is not None and remaining_ms() < reserve:
            raise CollectionBudgetExceeded("Stopped source work to reserve time for saving the run manifest")

    started = utc_now()
    run_id = uuid.uuid4().hex
    LOGGER.info(json.dumps({"event": "collection_started", "run_id": run_id, "cik": config["cik"], "started_at": started}, sort_keys=True))
    manifest = {
        "schema_version": 1,
        "run_id": run_id,
        "started_at": started,
        "cik": config["cik"],
        "forms": config["forms"],
        "limit": config["limit"],
        "status": "failed",
        "filings": [],
        "errors": [],
        "scope": "SEC recent submissions only; not a historical backfill or complete earnings packet",
    }
    try:
        require_time(SOURCE_RESERVE_MS + ARTIFACT_RESERVE_MS + MANIFEST_RESERVE_MS)
        payload, raw = sec.submissions(config["cik"])
        require_time(ARTIFACT_RESERVE_MS + MANIFEST_RESERVE_MS)
        manifest["submissions"] = save_artifact(s3, config["bucket"], raw, sec.submissions_url(config["cik"]), "application/json")
        filings = select_recent_filings(payload, forms=config["forms"], limit=config["limit"])
        for filing in filings:
            record = dict(filing)
            record["status"] = "failed"
            try:
                require_time(SOURCE_RESERVE_MS + ARTIFACT_RESERVE_MS + MANIFEST_RESERVE_MS)
                raw_document = sec.primary_document(config["cik"], filing["accession"], filing["primary_document"])
                source_url = sec.document_url(config["cik"], filing["accession"], filing["primary_document"])
                require_time(ARTIFACT_RESERVE_MS + MANIFEST_RESERVE_MS)
                record["artifact"] = save_artifact(s3, config["bucket"], raw_document, source_url, "application/octet-stream")
                record["status"] = "complete"
            except Exception as exc:
                if isinstance(exc, CollectionBudgetExceeded):
                    record["status"] = "deferred"
                record["error_type"] = type(exc).__name__
                manifest["errors"].append({"stage": "primary_document", "accession": filing["accession"], **error_details(exc)})
            manifest["filings"].append(record)
        manifest["status"] = "partial" if manifest["errors"] else "complete"
        manifest["no_matching_filings"] = not filings
    except Exception as exc:
        manifest["errors"].append({"stage": "submissions", **error_details(exc)})
    manifest["finished_at"] = utc_now()
    manifest_key = f"evidence/runs/{started[:10].replace('-', '/')}/{run_id}.json"
    if not put_new(s3, config["bucket"], manifest_key, json_bytes(manifest), "application/json"):
        raise RuntimeError("Run identifier collision; no manifest was replaced")
    result = {
        "status": manifest["status"],
        "run_id": run_id,
        "manifest_key": manifest_key,
        "filings_saved": sum(f["status"] == "complete" for f in manifest["filings"]),
        "error_count": len(manifest["errors"]),
        "no_matching_filings": manifest.get("no_matching_filings", False),
    }
    LOGGER.info(json.dumps({"event": "collection_finished", **result}, sort_keys=True))
    return result


def handler(event, context):
    """AWS Lambda entry point; events are triggers, not configuration inputs."""
    import boto3
    from botocore.config import Config

    config = configuration(os.environ)
    sec = SecClient(config["user_agent"], timeout=5)
    s3 = boto3.client("s3", config=Config(connect_timeout=2, read_timeout=5, retries={"total_max_attempts": 1, "mode": "standard"}))
    remaining_ms = getattr(context, "get_remaining_time_in_millis", None)
    result = collect(config, s3, sec, remaining_ms=remaining_ms)
    if result["status"] != "complete":
        # Returning {status: failed} alone would register as a successful Lambda
        # invocation, suppressing the Errors alarm. Raise after preserving evidence.
        raise RuntimeError(f"Collection {result['status']}; manifest={result['manifest_key']}")
    return result
